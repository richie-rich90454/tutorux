export function applyDocumentTailwindUtilities(): void {
    document.documentElement.classList.add(...rootUtilities.split(/\s+/u));
    document.body.classList.add(
        ..."w-full min-w-0 min-h-[100dvh] bg-canvas text-ink font-sans text-sm [font-variant-numeric:tabular-nums]".split(
            /\s+/u,
        ),
    );
    document.getElementById("root")?.classList.add(..."w-full min-w-0 min-h-full".split(/\s+/u));
}
